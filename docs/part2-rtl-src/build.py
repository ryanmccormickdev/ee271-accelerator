"""Assemble docs/part2-rtl.html from body.html + the walkthrough's style.css + rtl.css + app.js +
the recorded data (waves.json, facts.json), and build the "Read the code" tab from the real files
in part2/ (split into the blocks listed in regions.py). Standard library only.

Usage: python3 docs/part2-rtl-src/build.py [repo_root]

If the Part 2 conda environment exists, the generated defines.sv shown in the code reader is made
fresh with the staff's ivd-gv (and defines_p16.sv is refreshed); otherwise the checked-in copy is used.
Every block's first line (regions.py) must still be found in its file, or the build stops: a staff
update can't silently put a note next to the wrong code.
"""
import html
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
import regions  # noqa: E402

KIND_LABEL = {"design": "Part of the design", "given": "Given, don't edit", "yours": "You write this",
              "host": "The testbench (host)", "tool": "Build flow", "generated": "Generated by ivd-gv"}

# ------------------------------------------------------------------ tiny highlighters
SV_KW = (r"\b(?:module|endmodule|input|output|inout|wire|logic|reg|integer|int|string|parameter|localparam|assign|always|"
         r"always_ff|always_comb|initial|begin|end|if|else|case|endcase|for|forever|repeat|wait|posedge|negedge|or|"
         r"typedef|struct|packed|enum|task|endtask|function|endfunction|automatic|return|genvar|generate|endgenerate|"
         r"default|signed|unsigned)\b")
SV_TOKEN = re.compile(r"(?P<c>//.*$)|(?P<s>\"(?:[^\"\\]|\\.)*\")|(?P<d>`\w+|\$\w+)|(?P<k>" + SV_KW + r")|"
                      r"(?P<n>\b\d+'[sS]?[bodhBODH][0-9a-fA-FxXzZ_]+|'[01xXzZ]\b|\b\d+\b)")
MK_TOKEN = re.compile(r"(?P<c>#.*$)|(?P<d>\$\([A-Za-z_]+\)|\$\$\w+|\$\$\(|\$\w)|(?P<k>^[A-Za-z0-9_.]+(?=:))|(?P<s>\"(?:[^\"\\]|\\.)*\"|'[^']*')")


def highlight(line, lang):
    tok = SV_TOKEN if lang == "sv" else MK_TOKEN
    out, pos = [], 0
    for m in tok.finditer(line):
        out.append(html.escape(line[pos:m.start()]))
        out.append(f'<span class="tk-{m.lastgroup}">{html.escape(m.group())}</span>')
        pos = m.end()
    out.append(html.escape(line[pos:]))
    return "".join(out)


def code_html(first, lines, lang):
    out, yours = [], False
    for i, line in enumerate(lines):
        if "START IMPLEMENTATION" in line:
            yours = True
        cls = ' class="yours"' if yours else ""
        shown = line.replace("\t", "    ")
        out.append(f'<span{cls}><span class="ln">{first + i}</span>{highlight(shown, lang)}</span>')
        if "END IMPLEMENTATION" in line:
            yours = False
    return "".join(out)


# ------------------------------------------------------------------ splitting a file into its blocks
def split(text, blocks, label):
    lines = text.split("\n")
    while lines and lines[-1] == "":
        lines.pop()
    starts, pos = [], 0
    for b in blocks:
        # "then" (optional): the line after the block's first line must start with this too
        # (used for the testbench's three-line comment banners, whose first lines are all identical)
        i = next((k for k in range(pos, len(lines)) if lines[k].startswith(b["at"])
                  and ("then" not in b or (k + 1 < len(lines) and lines[k + 1].startswith(b["then"])))), None)
        if i is None:
            raise SystemExit(f"{label}: block start not found after line {pos + 1}: {b['at']!r} {b.get('then', '')!r}")
        starts.append(i)
        pos = i + 1
    if starts[0] != 0:
        raise SystemExit(f"{label}: the first block must start at line 1, found {starts[0] + 1}")
    out = []
    for n, (b, s) in enumerate(zip(blocks, starts)):
        e = starts[n + 1] if n + 1 < len(starts) else len(lines)
        while e > s + 1 and lines[e - 1].strip() == "":
            e -= 1
        out.append((b, s + 1, lines[s:e]))
    return out, len(lines)


def note_html(b, num):
    parts = [f'<div class="rhead"><span class="rnum">{num}</span><h4>{b["title"]}</h4><span class="kindtag">{KIND_LABEL[b["kind"]]}</span></div>',
             f'<div class="prose rwhat"><p>{b["what"]}</p></div>']
    if b.get("spec"):
        src, text = b["spec"]
        parts.append(f'<blockquote class="spec"><span class="src">{html.escape(src)} says:</span>{text}</blockquote>')
    if b.get("vals"):
        rows = "".join(f'<tr><th><code>{html.escape(k)}</code></th><td><pre>{html.escape(v)}</pre></td></tr>' for k, v in b["vals"])
        parts.append(f'<div class="valwrap"><div class="valhead">{html.escape(b.get("vals_caption", "Real values"))}</div><table class="vals">{rows}</table></div>')
    if b.get("todo"):
        parts.append(f'<div class="todo"><div class="todohead">What goes here, in words</div>{b["todo"]}</div>')
    if b.get("sv"):
        parts.append('<details class="py" open><summary>Reading the SystemVerilog</summary><ul>' + "".join(f"<li>{p}</li>" for p in b["sv"]) + "</ul></details>")
    if b.get("see"):
        parts.append('<div class="seeit">' + "".join(f'<button class="small" data-goto="{g}">{html.escape(lbl)}</button>' for lbl, g in b["see"]) + "</div>")
    return "".join(parts)


def file_id(path):
    return "cmf-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")


def defines_text():
    """The generated defines.sv (16 PEs, the staff defaults): fresh from ivd-gv if possible."""
    saved = os.path.join(HERE, "defines_p16.sv")
    py = os.path.join(REPO, "part2", "ee271-conda-env", "bin", "python")
    tool = os.path.join(REPO, "part2", "simulator", "bin", "ivd-gv")
    if os.path.exists(py) and os.path.exists(tool):
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, "defines.sv")
            r = subprocess.run([py, tool, "--out", out], capture_output=True, text=True)
            if r.returncode == 0 and os.path.exists(out):
                text = open(out).read()
                if not os.path.exists(saved) or open(saved).read() != text:
                    open(saved, "w").write(text)
                    print("refreshed defines_p16.sv from ivd-gv")
                return text
            print("ivd-gv failed, using the saved defines_p16.sv:", r.stderr.strip()[-200:])
    return open(saved).read()


def reader():
    bar, sections, seen_ids, total = {}, [], set(), 0
    files = regions.FILES
    for fi, f in enumerate(files):
        text = defines_text() if f["path"] == "GENERATED/defines.sv" else open(os.path.join(REPO, f["path"])).read()
        blocks, nlines = split(text, f["regions"], f["path"])
        fid = file_id(f["path"])
        shown = f.get("shown", f["path"])
        bar.setdefault(f["group"], []).append(
            f'<button class="rfbtn" data-file="{fid}"><code>{html.escape(shown.split("/")[-1])}</code><small>{html.escape(f["blurb"])}</small></button>')
        badge = {"yours": '<span class="badge yours">you finish this</span>', "generated": '<span class="badge given">generated, don\'t edit</span>'}.get(
            f["kind"], '<span class="badge given">given, don\'t edit</span>')
        rows = []
        for n, (b, first, lines) in enumerate(blocks, 1):
            rid = b.get("id") or f"{fid}-b{n}"
            if rid in seen_ids:
                raise SystemExit(f"duplicate block id {rid}")
            seen_ids.add(rid)
            rows.append(f'<div class="cblock k-{b["color"]} kind-{b["kind"]}" id="{rid}">'
                        f'<div class="rcode"><span class="rnum">{n}</span><pre class="code">{code_html(first, lines, f.get("lang", "sv"))}</pre></div>'
                        f'<div class="rnote">{note_html(b, n)}</div></div>')
        total += len(blocks)
        prev_btn = f'<button class="rfjump" data-file="{file_id(files[fi - 1]["path"])}">← {html.escape(files[fi - 1].get("shown", files[fi - 1]["path"]).split("/")[-1])}</button>' if fi else "<span></span>"
        next_btn = f'<button class="rfjump primary" data-file="{file_id(files[fi + 1]["path"])}">Next: {html.escape(files[fi + 1].get("shown", files[fi + 1]["path"]).split("/")[-1])} →</button>' if fi + 1 < len(files) else "<span></span>"
        sections.append(
            f'<section class="rfile" id="{fid}" data-file="{fid}" hidden>'
            f'<div class="rfhead"><div class="rftitle"><h3>{html.escape(shown)}</h3>{badge}'
            f'<span class="muted">{nlines} lines in {len(blocks)} blocks</span></div>'
            f'<p class="rfintro">{f["intro"]}</p></div>'
            f'<div class="reader">{"".join(rows)}</div>'
            f'<div class="rfnav">{prev_btn}{next_btn}</div></section>')
    bar_html = '<div class="rfbar" role="group" aria-label="Files">' + "".join(
        f'<div class="rfgroup"><span class="rfglabel">{html.escape(g)}</span><div class="rfgbtns">{"".join(btns)}</div></div>' for g, btns in bar.items()) + "</div>"
    return bar_html + "".join(sections), total, len(files)


def main():
    body = open(os.path.join(HERE, "body.html")).read()
    css = open(os.path.join(REPO, "docs", "walkthrough-src", "style.css")).read() + "\n/* ---- part2-rtl additions ---- */\n" + open(os.path.join(HERE, "rtl.css")).read()
    waves = json.load(open(os.path.join(HERE, "waves.json")))
    facts = json.load(open(os.path.join(HERE, "facts.json")))
    data = json.dumps({"waves": waves, "facts": facts}, separators=(",", ":")).replace("</", "<\\/")
    rd, nblocks, nfiles = reader()
    for marker, value in (("/*STYLE*/", css), ("/*DATA*/", data), ("/*APP*/", open(os.path.join(HERE, "model.js")).read() + "\n" + open(os.path.join(HERE, "app.js")).read()), ("<!--READER-->", rd)):
        if marker not in body:
            raise SystemExit("missing marker " + marker)
        body = body.replace(marker, value)
    prose = re.sub(r"<script[\s\S]*?</script>|<pre[^>]*>[\s\S]*?</pre>|<style>[\s\S]*?</style>|<code>[\s\S]*?</code>", "", body)
    left = [(m.group(), prose[max(0, m.start() - 60):m.end() + 20]) for m in re.finditer(r"TODO|FIXME|XXX|\{\{|\}\}|\bundefined\b|\bNaN\b", prose)]
    if left:
        raise SystemExit("placeholder text left in the page:\n" + "\n".join(f"  {w!r} in ...{c!r}..." for w, c in left[:10]))
    out = os.path.join(REPO, "docs", "part2-rtl.html")
    open(out, "w").write(body)
    print(f"wrote {out} ({len(body):,} bytes; code reader: {nfiles} files, {nblocks} blocks)")


if __name__ == "__main__":
    main()
